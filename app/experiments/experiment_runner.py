"""
Experiment Runner.

This module executes PyTorch experiments generated by the
CodeGenerationAgent.

Workflow:

    CodeGenerationAgent
            |
            v
    generated_experiment.py
            |
            v
    ExperimentRunner
            |
            +--> Prepare experiment directory
            +--> Execute generated Python code
            +--> Capture stdout/stderr
            +--> Monitor execution
            +--> Collect metrics
            +--> Collect training history
            +--> Locate checkpoint
            +--> Locate visualizations
            |
            v
    Standardized Experiment Result

The ExperimentRunner is responsible for EXECUTION and RESULT
COLLECTION. It does not generate machine-learning code itself.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional


class ExperimentRunner:
    """
    Execute and collect results from generated PyTorch experiments.

    The runner is intentionally separated from CodeGenerationAgent:

        CodeGenerationAgent
            -> generates experiment code

        ExperimentRunner
            -> executes experiment code
            -> collects experiment outputs
    """

    DEFAULT_TIMEOUT_SECONDS = 7200

    DEFAULT_OUTPUT_FILES = {
        "metrics": "metrics.json",
        "training_history": "training_history.json",
        "summary": "experiment_summary.json",
        "checkpoint": "best_model.pt",
    }

    DEFAULT_VISUALIZATION_EXTENSIONS = {
        ".png",
        ".jpg",
        ".jpeg",
        ".svg",
        ".pdf",
    }

    def __init__(
        self,
        output_directory: str | Path = "experiment_runs",
        timeout_seconds: Optional[int] = None,
        python_executable: Optional[str] = None,
    ):
        """
        Initialize the Experiment Runner.

        Parameters
        ----------
        output_directory:
            Root directory where experiment runs are stored.

        timeout_seconds:
            Maximum execution time for one experiment.

        python_executable:
            Python interpreter used to execute generated code.
            Defaults to the current Python interpreter.
        """

        self.output_directory = Path(output_directory)

        self.timeout_seconds = (
            self.DEFAULT_TIMEOUT_SECONDS
            if timeout_seconds is None
            else max(1, int(timeout_seconds))
        )

        self.python_executable = (
            python_executable
            or sys.executable
        )

        self.output_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

    # ============================================================
    # Utility
    # ============================================================

    @staticmethod
    def _timestamp() -> str:
        """
        Generate a filesystem-safe timestamp.
        """

        return datetime.now().strftime(
            "%Y%m%d_%H%M%S"
        )

    @staticmethod
    def _read_json(
        path: Path,
    ) -> Optional[Dict[str, Any]]:
        """
        Read a JSON file.

        Returns None if the file does not exist or cannot
        be parsed.
        """

        if not path.exists():
            return None

        try:
            with path.open(
                "r",
                encoding="utf-8",
            ) as file:
                data = json.load(file)

            if isinstance(data, dict):
                return data

            return {
                "value": data
            }

        except Exception:
            return None

    @staticmethod
    def _write_json(
        path: Path,
        data: Any,
    ) -> None:
        """
        Write JSON data to disk.
        """

        path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        with path.open(
            "w",
            encoding="utf-8",
        ) as file:
            json.dump(
                data,
                file,
                indent=4,
                ensure_ascii=False,
                default=str,
            )

    # ============================================================
    # Experiment Directory
    # ============================================================

    def create_run_directory(
        self,
        run_name: Optional[str] = None,
    ) -> Path:
        """
        Create a unique directory for one experiment run.
        """

        if run_name:
            safe_name = "".join(
                character
                if character.isalnum()
                or character in (
                    "-",
                    "_",
                )
                else "_"
                for character in run_name
            )

            directory_name = (
                f"{safe_name}_{self._timestamp()}"
            )

        else:
            directory_name = (
                f"experiment_{self._timestamp()}"
            )

        run_directory = (
            self.output_directory
            / directory_name
        )

        run_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        return run_directory

    # ============================================================
    # Generated Code
    # ============================================================

    def prepare_generated_code(
        self,
        generated_code: str,
        run_directory: Path,
        filename: str = "generated_experiment.py",
    ) -> Path:
        """
        Save generated PyTorch code into the experiment
        run directory.
        """

        if not isinstance(
            generated_code,
            str,
        ):
            raise TypeError(
                "Generated code must be a string."
            )

        if not generated_code.strip():
            raise ValueError(
                "Generated code is empty."
            )

        code_path = (
            run_directory
            / filename
        )

        code_path.write_text(
            generated_code,
            encoding="utf-8",
        )

        return code_path

    def copy_generated_code(
        self,
        source_path: str | Path,
        run_directory: Path,
    ) -> Path:
        """
        Copy an existing generated Python file into
        the experiment run directory.
        """

        source = Path(source_path)

        if not source.exists():
            raise FileNotFoundError(
                f"Generated experiment was not found: {source}"
            )

        if source.suffix.lower() != ".py":
            raise ValueError(
                "Generated experiment must be a Python (.py) file."
            )

        destination = (
            run_directory
            / "generated_experiment.py"
        )

        destination.write_bytes(
            source.read_bytes()
        )

        return destination

    # ============================================================
    # Experiment Specification
    # ============================================================

    def save_experiment_metadata(
        self,
        run_directory: Path,
        generated_result: Optional[
            Dict[str, Any]
        ] = None,
        dataset_path: Optional[
            str | Path
        ] = None,
    ) -> Path:
        """
        Save metadata describing the experiment run.

        This stores the model recommendation, experiment plan,
        assumptions, dependencies, and dataset path generated
        by CodeGenerationAgent.
        """

        generated_result = (
            generated_result
            if isinstance(
                generated_result,
                dict,
            )
            else {}
        )

        metadata = {
            "created_at": datetime.now().isoformat(),
            "dataset_path": (
                str(dataset_path)
                if dataset_path is not None
                else None
            ),
            "model": generated_result.get(
                "model"
            ),
            "model_recommendation": generated_result.get(
                "model_recommendation"
            ),
            "experiment_plan": generated_result.get(
                "experiment_plan"
            ),
            "assumptions": generated_result.get(
                "assumptions",
                [],
            ),
            "dependencies": generated_result.get(
                "dependencies",
                [],
            ),
        }

        metadata_path = (
            run_directory
            / "experiment_metadata.json"
        )

        self._write_json(
            metadata_path,
            metadata,
        )

        return metadata_path

    # ============================================================
    # Process Environment
    # ============================================================

    def build_environment(
        self,
        run_directory: Path,
        dataset_path: Optional[
            str | Path
        ] = None,
    ) -> Dict[str, str]:
        """
        Build the environment variables supplied to the generated
        experiment.

        The generated code can use these variables when needed:

            EXPERIMENT_OUTPUT_DIR
            DATASET_PATH
        """

        environment = os.environ.copy()

        environment[
            "EXPERIMENT_OUTPUT_DIR"
        ] = str(
            run_directory
        )

        if dataset_path is not None:
            environment[
                "DATASET_PATH"
            ] = str(
                Path(dataset_path).resolve()
            )

        return environment

    # ============================================================
    # Execute Experiment
    # ============================================================

    def execute(
        self,
        code_path: str | Path,
        run_directory: Path,
        dataset_path: Optional[
            str | Path
        ] = None,
    ) -> Dict[str, Any]:
        """
        Execute the generated Python experiment.

        Returns a structured execution result.
        """

        code_path = Path(code_path).resolve()

        if not code_path.exists():
            raise FileNotFoundError(
                f"Experiment code does not exist: {code_path}"
            )

        stdout_path = (
            run_directory
            / "stdout.log"
        )

        stderr_path = (
            run_directory
            / "stderr.log"
        )

        command = [
            self.python_executable,
            str(code_path),
        ]

        started_at = datetime.now()

        start_time = time.perf_counter()

        result: Dict[str, Any] = {
            "success": False,
            "status": "not_started",
            "return_code": None,
            "command": command,
            "started_at": started_at.isoformat(),
            "finished_at": None,
            "execution_seconds": None,
            "timeout_seconds": self.timeout_seconds,
            "stdout": "",
            "stderr": "",
            "stdout_path": str(stdout_path),
            "stderr_path": str(stderr_path),
            "error": None,
        }

        try:
            process = subprocess.run(
                command,
                cwd=str(run_directory),
                env=self.build_environment(
                    run_directory,
                    dataset_path,
                ),
                capture_output=True,
                text=True,
                timeout=self.timeout_seconds,
            )

            stdout = process.stdout or ""
            stderr = process.stderr or ""

            stdout_path.write_text(
                stdout,
                encoding="utf-8",
            )

            stderr_path.write_text(
                stderr,
                encoding="utf-8",
            )

            result.update(
                {
                    "return_code": process.returncode,
                    "stdout": stdout,
                    "stderr": stderr,
                    "success": (
                        process.returncode == 0
                    ),
                    "status": (
                        "completed"
                        if process.returncode == 0
                        else "failed"
                    ),
                }
            )

            if process.returncode != 0:
                result["error"] = (
                    "Generated experiment exited "
                    f"with return code {process.returncode}."
                )

        except subprocess.TimeoutExpired as error:
            stdout = (
                error.stdout
                if isinstance(
                    error.stdout,
                    str,
                )
                else ""
            )

            stderr = (
                error.stderr
                if isinstance(
                    error.stderr,
                    str,
                )
                else ""
            )

            stdout_path.write_text(
                stdout,
                encoding="utf-8",
            )

            stderr_path.write_text(
                stderr,
                encoding="utf-8",
            )

            result.update(
                {
                    "status": "timeout",
                    "stdout": stdout,
                    "stderr": stderr,
                    "error": (
                        "Experiment exceeded the execution "
                        f"timeout of {self.timeout_seconds} seconds."
                    ),
                }
            )

        except Exception as error:
            result.update(
                {
                    "status": "runner_error",
                    "error": str(error),
                }
            )

        finally:
            finished_at = datetime.now()

            result["finished_at"] = (
                finished_at.isoformat()
            )

            result["execution_seconds"] = (
                time.perf_counter()
                - start_time
            )

        return result

    # ============================================================
    # Output Collection
    # ============================================================

    def find_output_file(
        self,
        run_directory: Path,
        filename: str,
    ) -> Optional[Path]:
        """
        Find a named experiment output file.

        First checks the run root, then searches recursively.
        """

        direct_path = (
            run_directory
            / filename
        )

        if direct_path.exists():
            return direct_path

        matches = list(
            run_directory.rglob(filename)
        )

        if matches:
            return matches[0]

        return None

    def collect_metrics(
        self,
        run_directory: Path,
    ) -> Optional[Dict[str, Any]]:
        """
        Load metrics.json produced by the generated experiment.
        """

        path = self.find_output_file(
            run_directory,
            self.DEFAULT_OUTPUT_FILES[
                "metrics"
            ],
        )

        if path is None:
            return None

        return self._read_json(path)

    def collect_training_history(
        self,
        run_directory: Path,
    ) -> Optional[Dict[str, Any]]:
        """
        Load training_history.json produced by the generated
        experiment.
        """

        path = self.find_output_file(
            run_directory,
            self.DEFAULT_OUTPUT_FILES[
                "training_history"
            ],
        )

        if path is None:
            return None

        return self._read_json(path)

    def find_checkpoint(
        self,
        run_directory: Path,
    ) -> Optional[str]:
        """
        Locate the best model checkpoint.

        Supports common PyTorch checkpoint extensions.
        """

        preferred_names = [
            "best_model.pt",
            "best_model.pth",
            "best_checkpoint.pt",
            "best_checkpoint.pth",
            "checkpoint.pt",
            "checkpoint.pth",
        ]

        for filename in preferred_names:
            path = self.find_output_file(
                run_directory,
                filename,
            )

            if path is not None:
                return str(path)

        checkpoint_extensions = {
            ".pt",
            ".pth",
            ".ckpt",
        }

        for path in run_directory.rglob("*"):
            if (
                path.is_file()
                and path.suffix.lower()
                in checkpoint_extensions
            ):
                return str(path)

        return None

    def find_visualizations(
        self,
        run_directory: Path,
    ) -> List[str]:
        """
        Locate generated visualization files.
        """

        visualizations: List[str] = []

        for path in run_directory.rglob("*"):
            if (
                path.is_file()
                and path.suffix.lower()
                in self.DEFAULT_VISUALIZATION_EXTENSIONS
            ):
                visualizations.append(
                    str(path)
                )

        return sorted(
            visualizations
        )

    def collect_outputs(
        self,
        run_directory: Path,
    ) -> Dict[str, Any]:
        """
        Collect all standard experiment outputs.
        """

        metrics_path = self.find_output_file(
            run_directory,
            self.DEFAULT_OUTPUT_FILES[
                "metrics"
            ],
        )

        history_path = self.find_output_file(
            run_directory,
            self.DEFAULT_OUTPUT_FILES[
                "training_history"
            ],
        )

        summary_path = self.find_output_file(
            run_directory,
            self.DEFAULT_OUTPUT_FILES[
                "summary"
            ],
        )

        checkpoint_path = self.find_checkpoint(
            run_directory
        )

        visualizations = (
            self.find_visualizations(
                run_directory
            )
        )

        return {
            "metrics": (
                self._read_json(
                    metrics_path
                )
                if metrics_path
                else None
            ),
            "metrics_path": (
                str(metrics_path)
                if metrics_path
                else None
            ),
            "training_history": (
                self._read_json(
                    history_path
                )
                if history_path
                else None
            ),
            "training_history_path": (
                str(history_path)
                if history_path
                else None
            ),
            "experiment_summary": (
                self._read_json(
                    summary_path
                )
                if summary_path
                else None
            ),
            "experiment_summary_path": (
                str(summary_path)
                if summary_path
                else None
            ),
            "checkpoint_path": checkpoint_path,
            "visualizations": visualizations,
        }

    # ============================================================
    # Output Validation
    # ============================================================

    @staticmethod
    def validate_outputs(
        execution_result: Dict[str, Any],
        outputs: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Validate whether the experiment produced the expected
        outputs.
        """

        warnings: List[str] = []

        if execution_result.get(
            "success"
        ):
            if outputs.get(
                "metrics"
            ) is None:
                warnings.append(
                    "metrics.json was not found."
                )

            if outputs.get(
                "training_history"
            ) is None:
                warnings.append(
                    "training_history.json was not found."
                )

            if outputs.get(
                "checkpoint_path"
            ) is None:
                warnings.append(
                    "No PyTorch checkpoint was found."
                )

            if not outputs.get(
                "visualizations"
            ):
                warnings.append(
                    "No visualization files were found."
                )

        return {
            "valid": (
                execution_result.get(
                    "success",
                    False,
                )
                and not warnings
            ),
            "warnings": warnings,
        }

    # ============================================================
    # Complete Run
    # ============================================================

    def run(
        self,
        generated_code: Optional[str] = None,
        code_path: Optional[
            str | Path
        ] = None,
        dataset_path: Optional[
            str | Path
        ] = None,
        generated_result: Optional[
            Dict[str, Any]
        ] = None,
        run_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Execute a complete generated experiment.

        Either generated_code or code_path must be supplied.

        Parameters
        ----------
        generated_code:
            PyTorch source code returned by CodeGenerationAgent.

        code_path:
            Existing generated Python file.

        dataset_path:
            Local path to the 5G-NIDD dataset.

        generated_result:
            Optional complete result returned by CodeGenerationAgent.

        run_name:
            Optional human-readable experiment name.
        """

        total_start = time.perf_counter()

        result: Dict[str, Any] = {
            "success": False,
            "status": "not_started",
            "run_directory": None,
            "generated_code_path": None,
            "dataset_path": (
                str(dataset_path)
                if dataset_path is not None
                else None
            ),
            "execution": None,
            "outputs": None,
            "output_validation": None,
            "total_execution_seconds": None,
            "errors": [],
        }

        run_directory: Optional[Path] = None

        try:
            # ----------------------------------------------------
            # Validate code input
            # ----------------------------------------------------

            if (
                generated_code is None
                and code_path is None
            ):
                raise ValueError(
                    "Either generated_code or code_path "
                    "must be provided."
                )

            if (
                generated_code is not None
                and not isinstance(
                    generated_code,
                    str,
                )
            ):
                raise TypeError(
                    "generated_code must be a string."
                )

            # ----------------------------------------------------
            # Validate dataset path when supplied
            # ----------------------------------------------------

            if dataset_path is not None:
                dataset = Path(
                    dataset_path
                )

                if not dataset.exists():
                    raise FileNotFoundError(
                        "Dataset path does not exist: "
                        f"{dataset}"
                    )

            # ----------------------------------------------------
            # Create run directory
            # ----------------------------------------------------

            run_directory = (
                self.create_run_directory(
                    run_name
                )
            )

            result[
                "run_directory"
            ] = str(run_directory)

            # ----------------------------------------------------
            # Save metadata
            # ----------------------------------------------------

            self.save_experiment_metadata(
                run_directory,
                generated_result,
                dataset_path,
            )

            # ----------------------------------------------------
            # Prepare generated code
            # ----------------------------------------------------

            if generated_code is not None:
                experiment_code_path = (
                    self.prepare_generated_code(
                        generated_code,
                        run_directory,
                    )
                )

            else:
                experiment_code_path = (
                    self.copy_generated_code(
                        code_path,
                        run_directory,
                    )
                )

            result[
                "generated_code_path"
            ] = str(
                experiment_code_path
            )

            # ----------------------------------------------------
            # Execute
            # ----------------------------------------------------

            execution_result = (
                self.execute(
                    experiment_code_path,
                    run_directory,
                    dataset_path,
                )
            )

            result[
                "execution"
            ] = execution_result

            # ----------------------------------------------------
            # Collect outputs
            # ----------------------------------------------------

            outputs = (
                self.collect_outputs(
                    run_directory
                )
            )

            result[
                "outputs"
            ] = outputs

            # ----------------------------------------------------
            # Validate outputs
            # ----------------------------------------------------

            output_validation = (
                self.validate_outputs(
                    execution_result,
                    outputs,
                )
            )

            result[
                "output_validation"
            ] = output_validation

            # ----------------------------------------------------
            # Overall status
            # ----------------------------------------------------

            if execution_result.get(
                "success",
                False,
            ):
                result[
                    "success"
                ] = True

                if output_validation.get(
                    "warnings"
                ):
                    result[
                        "status"
                    ] = "completed_with_warnings"
                else:
                    result[
                        "status"
                    ] = "completed"

            else:
                result[
                    "status"
                ] = execution_result.get(
                    "status",
                    "failed",
                )

                if execution_result.get(
                    "error"
                ):
                    result[
                        "errors"
                    ].append(
                        execution_result[
                            "error"
                        ]
                    )

        except Exception as error:
            result[
                "status"
            ] = "runner_error"

            result[
                "errors"
            ].append(
                str(error)
            )

        finally:
            result[
                "total_execution_seconds"
            ] = (
                time.perf_counter()
                - total_start
            )

            # ----------------------------------------------------
            # Save final runner result
            # ----------------------------------------------------

            if run_directory is not None:
                result_path = (
                    run_directory
                    / "runner_result.json"
                )

                self._write_json(
                    result_path,
                    result,
                )

                result[
                    "runner_result_path"
                ] = str(
                    result_path
                )

        return result

    # ============================================================
    # CodeGenerationAgent Integration
    # ============================================================

    def run_generated_result(
        self,
        generated_result: Dict[str, Any],
        dataset_path: Optional[
            str | Path
        ] = None,
        run_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Execute the result returned directly by
        CodeGenerationAgent.generate().

        Expected input:

            {
                "success": True,
                "pytorch_code": "...",
                "model_recommendation": {...},
                "experiment_plan": {...},
                ...
            }
        """

        if not isinstance(
            generated_result,
            dict,
        ):
            raise TypeError(
                "generated_result must be a dictionary."
            )

        if not generated_result.get(
            "success",
            False,
        ):
            return {
                "success": False,
                "status": "generation_failed",
                "errors": (
                    generated_result.get(
                        "errors",
                        [
                            "Code generation failed."
                        ],
                    )
                ),
                "generation_result": generated_result,
            }

        generated_code = (
            generated_result.get(
                "pytorch_code"
            )
        )

        if not isinstance(
            generated_code,
            str,
        ):
            return {
                "success": False,
                "status": "invalid_generated_code",
                "errors": [
                    "CodeGenerationAgent did not return "
                    "valid pytorch_code."
                ],
            }

        return self.run(
            generated_code=generated_code,
            dataset_path=dataset_path,
            generated_result=generated_result,
            run_name=run_name,
        )
